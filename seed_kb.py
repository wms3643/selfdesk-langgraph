def main() -> None:
    db.init_db()
    existing = {d["title"] for d in pg_store.list_docs(limit=1000)}
    added = failed = 0

    for title, content in DOCS:
        if title in existing:
            continue
        # ingest 内部完成切分 + 向量化 + 同事务写入；标题重复会覆盖
        res = pg_store.ingest(title, content, rag.embed, source="seed")
        if res:
            added += 1
        else:
            failed += 1
            print(f"  ! 写入失败: {title}")

    print(f"新增 {added} 条，失败 {failed} 条，当前共 {pg_store.count()} 条")


if __name__ == "__main__":
    main()
